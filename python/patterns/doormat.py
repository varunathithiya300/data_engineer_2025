""" 
------------.|.------------
---------.|..|..|.---------
------.|..|..|..|..|.------
---.|..|..|..|..|..|..|.---
----------WELCOME----------
---.|..|..|..|..|..|..|.---
------.|..|..|..|..|.------
---------.|..|..|.---------
------------.|.------------ 

"""

a, b = map(int, input().split())

pattern = ".|."

for i in range(a//2):
    line = pattern*(2*i+1)
    print(line.center(b, "-"))

print("WELCOME".center(b, "-"))

for i in range(a//2 - 1, -1, -1):
    line = pattern*(2*i+1)
    print(line.center(b, "-"))